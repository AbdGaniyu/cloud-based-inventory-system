import type { Metadata } from "next";
import { Suspense } from "react";

import { PageHeader } from "@/components/shell/page-header";
import { PageSkeleton } from "@/components/shell/page-skeleton";
import { UpcomingScreen } from "@/components/shell/upcoming-screen";
import { requirePageAccess } from "@/server/auth/session";

export const metadata: Metadata = { title: "Customers" };

export default function Page() {
  return (
    <Suspense fallback={<PageSkeleton />}>
      <Content />
    </Suspense>
  );
}

async function Content() {
  await requirePageAccess("customer.view");
  return (
    <>
      <PageHeader title="Customers" description="Buyers, their balances and message history." />
      <UpcomingScreen step={8} summary="Customer profiles with plans, purchases, warranties and messages." />
    </>
  );
}
